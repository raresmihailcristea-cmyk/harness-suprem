    def validate_constraints(self) -> List[str]:
        """Validates all strict Apple App Store Connect character limits."""
        errors = []
        if len(self.app_name) > 30:
            errors.append(f"App Name exceeds 30 characters: {len(self.app_name)} chars")
        if len(self.app_subtitle) > 30:
            errors.append(f"App Subtitle exceeds 30 characters: {len(self.app_subtitle)} chars")
        if len(self.promotional_text) > 170:
            errors.append(f"Promotional Text exceeds 170 characters: {len(self.promotional_text)} chars")
        if len(self.description) > 4000:
            errors.append(f"Description exceeds 4000 characters: {len(self.description)} chars")
        if len(self.keywords) > 100:
            errors.append(f"Keywords exceed 100 characters: {len(self.keywords)} chars")
        if len(self.app_review_notes) > 4000:
            errors.append(f"App Review Notes exceed 4000 characters: {len(self.app_review_notes)} chars")
        if len(self.app_encryption_doc) > 300:
            errors.append(f"App Encryption Doc exceeds 300 characters: {len(self.app_encryption_doc)} chars")
        if len(self.beta_app_description) > 4000:
            errors.append(f"Beta App Description exceeds 4000 characters: {len(self.beta_app_description)} chars")
        return errors

