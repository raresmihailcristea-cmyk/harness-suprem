        # App Encryption Documentation (<= 300 chars)
        if stats["has_custom_crypto"]:
            encryption_doc = "App implements standard cryptographic protocols and HTTPS/TLS for secure client-server communication. Complies with US EAR section 740.17 exemptions."[:300]
