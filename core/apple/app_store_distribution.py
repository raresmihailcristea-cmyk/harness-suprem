    @classmethod
    def _discover_identity(cls, project_dir: str) -> Tuple[str, str]:
        """Universally resolves App Name and Bundle Identifier from Xcode, SPM, or files."""
        app_name = None
        bundle_id = None

        # 1. Search Info.plist files
        for root, _, files in os.walk(project_dir):
            if "Info.plist" in files:
                plist_file = os.path.join(root, "Info.plist")
                try:
                    with open(plist_file, "r", encoding="utf-8", errors="ignore") as f:
                        text = f.read()
                    
                    # Display name or Bundle Name
                    m_disp = re.search(r"<key>CFBundleDisplayName</key>\s*<string>([^<]+)</string>", text)
                    m_name = re.search(r"<key>CFBundleName</key>\s*<string>([^<]+)</string>", text)
                    m_bid = re.search(r"<key>CFBundleIdentifier</key>\s*<string>([^<]+)</string>", text)

                    if m_disp and not m_disp.group(1).startswith("$"):
                        app_name = m_disp.group(1)
                    elif m_name and not m_name.group(1).startswith("$") and not app_name:
                        app_name = m_name.group(1)

                    if m_bid and not m_bid.group(1).startswith("$"):
                        bundle_id = m_bid.group(1)
                except Exception:
                    pass

        # 2. Search project.pbxproj
        if not app_name or not bundle_id:
            for root, _, files in os.walk(project_dir):
                if "project.pbxproj" in files:
                    pbx_file = os.path.join(root, "project.pbxproj")
                    try:
                        with open(pbx_file, "r", encoding="utf-8", errors="ignore") as f:
                            pbx = f.read()
                        if not app_name:
                            p_match = re.search(r"PRODUCT_NAME\s*=\s*[\"']?([^;\"']+)[\"']?;", pbx)
                            if p_match and not p_match.group(1).startswith("$"):
                                app_name = p_match.group(1).strip()
                        if not bundle_id:
                            bid_match = re.search(r"PRODUCT_BUNDLE_IDENTIFIER\s*=\s*[\"']?([^;\"']+)[\"']?;", pbx)
                            if bid_match and not bid_match.group(1).startswith("$"):
                                bundle_id = bid_match.group(1).strip()
                    except Exception:
                        pass

        # 3. Search Package.swift
        if not app_name:
            pkg_file = os.path.join(project_dir, "Package.swift")
            if os.path.exists(pkg_file):
                try:
                    with open(pkg_file, "r", encoding="utf-8", errors="ignore") as f:
                        pkg_text = f.read()
                    name_m = re.search(r'name:\s*"([^"]+)"', pkg_text)
                    if name_m:
                        app_name = name_m.group(1)
                except Exception:
                    pass

        # Fallback to directory name
        if not app_name:
            dir_base = os.path.basename(os.path.abspath(project_dir))
            clean_name = re.sub(r"[^a-zA-Z0-9\s_-]", "", dir_base).replace("-", " ").replace("_", " ").title()
            app_name = clean_name.strip() or "Universal Application"

        if not bundle_id:
            clean_slug = re.sub(r"[^a-z0-9]", "", app_name.lower())
            bundle_id = f"com.developer.{clean_slug}"

        return app_name, bundle_id

