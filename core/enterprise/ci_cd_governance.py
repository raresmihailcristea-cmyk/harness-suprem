from __future__ import annotations
import json
import logging
import re
from typing import Any, Dict, List, Optional

logger = logging.getLogger("core.enterprise.cicd")

class CICDGovernanceTool:
    """Provides enterprise CI/CD pipeline synthesis, build log triage, and cloud deployment governance."""

    @staticmethod
    def generate_pipeline_yaml(
        project_name: str,
        stack: str = "python",
        test_command: str = "pytest tests/",
        deploy_target: str = "docker",
    ) -> str:
        """Generates a standardized, secure CI/CD pipeline configuration."""
        if stack == "python":
            return f"""# Generated by Supreme Harness CI/CD Governance
name: {project_name}-ci
pipeline:
  stages:
    - name: lint_and_quality_gate
      steps:
        - run: ./apex-wrapper.sh --gate
    - name: test_and_evaluate
      steps:
        - run: {test_command}
    - name: build_and_push
      steps:
        - run: docker build -t {project_name}:latest .
        - run: echo "Deployment target: {deploy_target}"
"""
        elif stack in ["node", "typescript"]:
            return f"""# Generated by Supreme Harness CI/CD Governance
name: {project_name}-ci
pipeline:
  stages:
    - name: verify
      steps:
        - run: npm run lint
        - run: npm test
    - name: build
      steps:
        - run: npm run build
"""
        return f"# Custom pipeline for {project_name}\nsteps:\n  - run: {test_command}\n"

    @staticmethod
    def triage_failure_log(log_content: str) -> Dict[str, Any]:
        """Triages CI/CD failure logs to extract root causes, failed tests, and stack traces."""
        error_lines = []
        failed_tests = []

        root_cause_candidate = None
        for line in log_content.splitlines():
            line_strip = line.strip()
            if line_strip.startswith("ERROR:") or "Exception:" in line_strip:
                root_cause_candidate = line_strip
            elif ("FAILED" in line_strip or "ERROR" in line_strip) and not root_cause_candidate:
                error_lines.append(line_strip)

            # Pytest format: test_path::test_name FAILED
            m_pytest = re.search(r"^([a-zA-Z0-9_./:\-]+)\s+(?:FAILED|FAIL)", line_strip)
            # Unittest format: FAIL: test_name
            m_unittest = re.search(r"(?:FAIL|FAILED):\s*([a-zA-Z0-9_./:\-]+)", line_strip)
            if m_pytest:
                failed_tests.append(m_pytest.group(1))
            elif m_unittest:
                failed_tests.append(m_unittest.group(1))

        root_cause = root_cause_candidate or (error_lines[0] if error_lines else "Unknown failure")
        return {
            "root_cause": root_cause,
            "failed_tests_count": len(failed_tests),
            "failed_tests": failed_tests[:10],
            "sample_errors": error_lines[:5],
        }

    @staticmethod
    def estimate_deployment_cost(
        vcpus: int = 2,
        memory_gb: int = 4,
        hours_per_month: int = 730,
    ) -> Dict[str, float]:
        """Provides instant FinOps cost estimation for cloud execution environments."""
        # Standard cloud VM baseline pricing (~$0.035 per vCPU-hour, ~$0.0045 per GB-hour)
        vcpu_rate = 0.035
        mem_rate = 0.0045
        compute_cost = vcpus * vcpu_rate * hours_per_month
        mem_cost = memory_gb * mem_rate * hours_per_month
        total = compute_cost + mem_cost

        return {
            "vcpus": float(vcpus),
            "memory_gb": float(memory_gb),
            "estimated_monthly_usd": round(total, 2),
            "estimated_hourly_usd": round(total / hours_per_month, 4),
        }
